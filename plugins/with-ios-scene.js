const { withDangerousMod, withInfoPlist } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const SCENE_MARKER = "// @generated by with-ios-scene";
const SCENE_DELEGATE = `${SCENE_MARKER}
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate else {
      return
    }

    window = appDelegate.window
    window?.windowScene = windowScene
    window?.makeKeyAndVisible()
  }
}
`;

function withSceneManifest(config) {
  return withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            ConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return config;
  });
}

function withSceneDelegate(config) {
  return withDangerousMod(config, ["ios", async (config) => {
    const appDelegatePath = path.join(
      config.modRequest.platformProjectRoot,
      config.modRequest.projectName,
      "AppDelegate.swift"
    );
    const contents = fs.readFileSync(appDelegatePath, "utf8");
    if (!contents.includes(SCENE_MARKER)) {
      fs.writeFileSync(appDelegatePath, `${contents.trimEnd()}\n\n${SCENE_DELEGATE}`);
    }
    return config;
  }]);
}

module.exports = function withIOSScene(config) {
  return withSceneDelegate(withSceneManifest(config));
};
